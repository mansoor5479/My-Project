//switch case 

switch (true) {
    case 10 > 20:
        myAnswer = "red color"
        break;
    case 20 < 20:
        myAnswer = "green color"
        break;
    case 50 > 100:
        myAnswer = "blue color"
        break;
    case 100 != 100:
        myAnswer = "Yellow color"
        break;
    default:
        myAnswer = "Wrong Answer"
        break;
}
document.write(myAnswer)