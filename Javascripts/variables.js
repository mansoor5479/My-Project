//Variable declared by var keyword - can be redefined and values can be changed

var alpha = "This is Var keyword";
var alpha = "This is another variable with var keyword...<br>";
// to display the value in browser
document.write(alpha);

//Variable declared by let keyword - cannot be redefined and values can be changed

let beta = "This is Let keyword....<br>";
//let beta = "This is another variable Let keyword.... ";
document.write(beta);



//Variable declared by const keyword - neither redefined not value can change

const gama = "This is gama keyword...";
//const gama = "This is another vaariable with const keyword"
document.write(gama);